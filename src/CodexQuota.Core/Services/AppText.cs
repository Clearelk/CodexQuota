    public static string Template(AppLanguage language, string key)
    {
        var entry = Entries[key];
        return language == AppLanguage.English ? entry.English : entry.Chinese;
    }

    public static string Format(AppLanguage language, string key, params object?[] arguments) =>
        string.Format(CultureInfo.InvariantCulture, Template(language, key), arguments);

    public static string Count(AppLanguage language, long count, string singularKey, string pluralKey) =>
        Format(language, count == 1 ? singularKey : pluralKey, count);
