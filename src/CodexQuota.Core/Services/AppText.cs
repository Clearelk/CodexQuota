namespace CodexQuota.Core.Services;

/// <summary>A deferred app-owned message. Parameters retain data, paths and provider identifiers verbatim.</summary>
public sealed record AppMessage
{
    public AppMessage(string key, params object?[] arguments)
    {
        Key = key;
        Arguments = Array.AsReadOnly((object?[])arguments.Clone());
    }

    public string Key { get; }
    public IReadOnlyList<object?> Arguments { get; }
    public string Format(AppLanguage language = AppLanguage.SimplifiedChinese) => AppText.Format(language, Key, Arguments.ToArray());

    /// <summary>Honors an existing caller's explicit string override on an immutable snapshot.</summary>
    public string? FormatCompatible(AppLanguage language, string? compatibilityText) =>
        compatibilityText == Format() ? Format(language) : compatibilityText;
}

